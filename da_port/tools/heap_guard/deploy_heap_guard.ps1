# [DA_PORT] Сборка отдельного каталога с контролем кучи. Разбор — docs/17_HEAP_GUARD.md.
#
# ЗАЧЕМ ОТДЕЛЬНЫЙ КАТАЛОГ, а не подмена библиотек в bin. Контроль кучи делает кадры заметно тяжелее
# и съедает память под карантин. Если положить его в рабочий bin, то любой следующий замер
# производительности окажется испорчен, а понять это по игре нельзя — она просто «стала медленнее».
# Так уже выходило с набором библиотек: массовое копирование уронило FPS с 242 до 130, и разбираться
# пришлось задним числом. Здесь два каталога живут рядом и не мешают друг другу.
#
# ⛔ Копируются ТОЛЬКО живые файлы. В bin накопились десятки резервных копий (.old, .release_backup,
# .before_*, .disabled) — они отбираются по расширению: у резервных копий расширение как раз и есть
# сам суффикс, поэтому фильтр по .dll/.exe/.ini/.txt отсекает их все и ничего не пропускает.

param(
    [string]$GameRoot  = "D:\Dead Air\Dead Air",
    [string]$BuildBin  = "D:\Dead Air\xray-16\bin\AMD64\Release",

    # Библиотеки, которые МОЖНО положить быстрыми поверх релизных, — список ЯВНЫЙ и поимённый.
    #
    # ⛔ Не общий выключатель проверки. Смысл заслона в том, чтобы подмена конфигурации никогда не
    # случалась незаметно; осознанная подмена должна быть названа здесь и видна в выводе. xrPhysics
    # попадает сюда потому, что заслон негодной геометрии (задача #66) живёт именно в ней, а
    # релизную мы не собираем.
    [string[]]$Slower = @("xrPhysics.dll"),

    # Имя каталога сборки с контролем. Вынесено в настройку не для красоты: файл в старом каталоге
    # может оказаться захвачен намертво (наблюдалось с xrGame.dll — владельца не назвал ни обзор
    # модулей, ни переименование), и тогда единственный быстрый выход — разложить рядом заново.
    [string]$DstName = "bin_heapguard"
)

$ErrorActionPreference = "Stop"

$src = Join-Path $GameRoot "bin"
$dst = Join-Path $GameRoot $DstName

# ⛔ Заслон: подменять библиотеки под работающей игрой нельзя — файлы держатся открытыми, копирование
# пройдёт наполовину, и получится набор из двух разных сборок.
#
# ⚠️ Но условие здесь ТОЧНОЕ, а не «игра вообще запущена». Читать bin у работающей игры безопасно
# (образы открыты с разделением на чтение), а пишем мы в отдельный каталог, где ничего не открыто.
# Опасен ровно один случай: запущена сама сборка с контролем, и мы целимся в её же файлы. Широкий
# заслон запрещал бы безобидное и заставлял закрывать игру там, где это не нужно.
$running = Get-Process xrEngine, xr_3da -ErrorAction SilentlyContinue
foreach ($proc in $running) {
    $path = try { $proc.Path } catch { $null }
    if ($path -and $path.StartsWith($dst, [StringComparison]::OrdinalIgnoreCase)) {
        throw "Запущена сама сборка с контролем (PID $($proc.Id)). Закройте её и повторите."
    }
}
if ($running) {
    Write-Host "· обычная игра запущена (PID $($running.Id -join ', ')) — это не мешает: её каталог только читается"
}

if (-not (Test-Path $src))      { throw "Не найден каталог игры: $src" }
if (-not (Test-Path $BuildBin)) { throw "Не найден выход сборки: $BuildBin" }

# Что кладём поверх переноса из bin: РОВНО те библиотеки, в которых живут наши правки.
#
#   xrCore          контроль кучи (da_heap_guard) и пометка прогона в логе
#   xrGame          заслоны кросс-таблицы, команды обхода локаций
#   xrRenderPC_R4   висячий указатель SH в компиляторе шейдеров
#
# ⚠️ Список сначала был из двух — и правка рендера уехала бы мимо, выложилась бы половина починки.
#
# ⛔ Но и расширять его «на всякий случай» НЕЛЬЗЯ, это проверено дорого. В список попал
# xrScriptEngine, которого наши правки не касаются вовсе. В игре он РЕЛИЗНЫЙ (1 037 210 байт), а
# из build_mingw кладётся быстрый (-Og, 1 644 970 — на 59% больше и без оптимизации). Через него
# идёт весь Lua, и на обходе локаций с ускорением времени ×1000 заходы разбухли со 150 до 480
# секунд, упёршись в таймаут. Сводка честно доложила «не завершилась» — по причине
# производительности, а не дефекта. То есть лишняя библиотека в списке не просто замедляет, она
# ПОДДЕЛЫВАЕТ результат проверки.
$editable = @("xrCore.dll", "xrGame.dll", "xrRenderPC_R4.dll", "xrPhysics.dll")

# Свежесть: собранные библиотеки обязаны быть новее исходников контроля. Иначе выложим вчерашнее и
# будем искать причину, почему в логе нет строки про карантин.
foreach ($name in $editable) {
    $f = Join-Path $BuildBin $name
    if (-not (Test-Path $f)) { throw "Не собрано: $f" }
}

# ⛔ САМОЛЕЧЕНИЕ ОТ ЗАХВАЧЕННОГО ФАЙЛА.
#
# Наблюдение, стоившее часа: после прогона `xrGame.dll` (128 МБ, самая крупная библиотека) остаётся
# захвачен МОНОПОЛЬНО и не отпускается — ни через минуту, ни через двадцать. Владельца назвать не
# удалось: процессов игры нет, обзор модулей всех процессов пуст, переименование тоже не проходит.
# Повторяется в ЛЮБОМ каталоге, включая только что созданный.
#
# Бороться с этим дальше — тратить время на чужую загадку вместо работы. Поэтому: если положить не
# удалось, берём соседний каталог с номером. Старый остаётся лежать и уберётся, когда отпустят.
if (Test-Path $dst) {
    $probe = Join-Path $dst "xrGame.dll"
    if (Test-Path $probe) {
        $free = $false
        try { $h = [IO.File]::Open($probe, 'Open', 'Write', 'None'); $h.Close(); $free = $true } catch {}
        if (-not $free) {
            for ($k = 2; $k -le 20; ++$k) {
                $try_dst = Join-Path $GameRoot ("{0}{1}" -f $DstName, $k)
                $try_probe = Join-Path $try_dst "xrGame.dll"
                if (-not (Test-Path $try_probe)) { $dst = $try_dst; break }
                try { $h = [IO.File]::Open($try_probe, 'Open', 'Write', 'None'); $h.Close(); $dst = $try_dst; break } catch {}
            }
            $DstName = Split-Path $dst -Leaf
            Write-Host "  ⚠️ прежний каталог занят намертво — раскладываю в $DstName"
        }
    }
}

Write-Host "Каталог с контролем кучи: $dst"
if (-not (Test-Path $dst)) { New-Item -ItemType Directory -Path $dst | Out-Null }

# ⚠️ Копируем только ИЗМЕНИВШЕЕСЯ. Раньше переносились все 68 файлов каждый раз, включая 59 МБ
# nvngx_dlss.dll, и выкладка регулярно спотыкалась: только что снятый процесс ещё не отпустил
# библиотеку, а мы уже пишем поверх. Совпадающие по размеру и времени файлы трогать незачем.
$live = @(".dll", ".exe", ".ini", ".txt")
$copied = 0
$skipped = 0
Get-ChildItem $src -File | Where-Object { $live -contains $_.Extension } | ForEach-Object {
    # ⛔ Наши библиотеки из bin НЕ переносим: строкой ниже они всё равно кладутся из сборки. Иначе
    # копируется впустую больше сотни мегабайт, и именно на этом выкладка спотыкалась о ещё
    # удерживаемый файл — переписывая то, что через секунду перепишем снова.
    if ($editable -contains $_.Name) { return }

    $target = Join-Path $dst $_.Name
    if ((Test-Path $target) -and
        ((Get-Item $target).Length -eq $_.Length) -and
        ((Get-Item $target).LastWriteTimeUtc -eq $_.LastWriteTimeUtc)) {
        $skipped++
        return
    }
    Copy-Item $_.FullName -Destination $dst -Force
    $copied++
}
Write-Host "  из bin: перенесено $copied, не изменилось $skipped"

# Поверх — правимый набор. Всё остальное берётся из рабочего каталога как есть, включая шесть
# перф-критичных релизных: их пересборка быстрой ничего бы не дала для поиска ошибок, а сборку
# замедлила бы ещё сильнее.
# ⛔ ЗАСЛОН ОТ ПОДМЕНЫ РЕЛИЗНОЙ БИБЛИОТЕКИ БЫСТРОЙ.
#
# Ради чего: перф-критичные библиотеки в игре собраны релизно, а build_mingw даёт быстрые (-Og).
# Подменить одну такую — значит замедлить игру в разы, ничего при этом не сломав внешне. На обходе
# локаций это уже случилось с xrScriptEngine: заходы разбухли со 150 до 480 секунд и упёрлись в
# таймаут, а сводка доложила «не завершилась» — то есть проверка не провалилась, а СОВРАЛА.
#
# Быстрая сборка ЗАМЕТНО крупнее релизной (нет оптимизации, больше отладочных данных), поэтому
# скачок размера — надёжный признак. Порог 20% отделяет смену конфигурации от обычной правки кода.
foreach ($name in $editable) {
    $src_file = Join-Path $BuildBin $name
    $game_file = Join-Path $src $name

    if (Test-Path $game_file) {
        $game_size = (Get-Item $game_file).Length
        $new_size = (Get-Item $src_file).Length
        $grow = if ($game_size) { ($new_size - $game_size) / $game_size } else { 0 }

        if ($grow -gt 0.20) {
            if ($Slower -contains $name) {
                Write-Host ("  ⚠️ {0}: быстрая поверх релизной (+{1:P0}) — РАЗРЕШЕНО ЯВНО. Физика будет медленнее." -f $name, $grow)
            }
            else {
                Write-Host ""
                Write-Host ("⛔ {0}: в игре {1:N0} байт, кладём {2:N0} (+{3:P0})." -f $name, $game_size, $new_size, $grow)
                Write-Host    "   Похоже на подмену РЕЛИЗНОЙ библиотеки БЫСТРОЙ. Это замедлит прогон в разы"
                Write-Host    "   и подделает результат проверки. Убедитесь, что наша правка вообще в ней есть,"
                Write-Host    "   и если подмена нужна намеренно — назовите библиотеку в -Slower."
                throw "выкладка остановлена: $name выглядит как смена конфигурации, а не как правка"
            }
        }
    }

    # ⛔ Уже лежит ровно то же самое — не трогаем. Не оптимизация: переписывание неизменившейся
    # библиотеки регулярно упиралось в чужой монопольный захват файла (не процессом игры — по
    # модулям владелец не находится, и даже переименование не проходит). Выкладка падала на копии,
    # которая ничего бы не изменила.
    $already = Join-Path $dst $name
    if ((Test-Path $already) -and
        ((Get-Item $already).Length -eq (Get-Item $src_file).Length) -and
        ((Get-Item $already).LastWriteTimeUtc -eq (Get-Item $src_file).LastWriteTimeUtc)) {
        Write-Host ("  без изменений: {0}" -f $name)
        continue
    }

    # 🪤 Повтор с паузой. Сразу после снятия игры файл ещё бывает занят, причём НЕ процессом игры:
    # проверка по модулям всех процессов не находит владельца, а запись не проходит. Похоже на
    # антивирус, дочитывающий только что изменённую стомегабайтную библиотеку. Одна попытка здесь
    # означает «выкладка через раз», поэтому их пять.
    $copied_ok = $false
    for ($try = 1; $try -le 5; ++$try) {
        try {
            Copy-Item $src_file -Destination $dst -Force -ErrorAction Stop
            $copied_ok = $true
            break
        }
        catch {
            if ($try -eq 5) { throw }
            Write-Host ("    {0}: занят, повтор через 3с ({1}/5)" -f $name, $try)
            Start-Sleep -Seconds 3
        }
    }

    $f = Get-Item (Join-Path $dst $name)
    Write-Host ("  подменено: {0,-18} {1,12:N0}  {2:yyyy-MM-dd HH:mm}" -f $name, $f.Length, $f.LastWriteTime)
}

# Что осталось от игры нетронутым — печатается всегда, чтобы разница была видна без раскопок.
Write-Host ""
Write-Host "  из игры взято как есть (включая перф-критичные релизные):"
Get-ChildItem $dst -File | Where-Object { $_.Extension -eq '.dll' -and $editable -notcontains $_.Name } |
    ForEach-Object { $_.Name } | Sort-Object |
    ForEach-Object { Write-Host ("    {0}" -f $_) }

# Запуск кладётся в КОРЕНЬ игры: рабочий каталог обязан быть там, иначе движок не найдёт fsgame.ltx
# и, как следствие, gamedata. Сами библиотеки при этом грузятся из каталога исполняемого файла, то
# есть из bin_heapguard, — так устроен порядок поиска в Windows, и подменять ничего не нужно.
$runner = Join-Path $GameRoot "ЗАПУСК_контроль_кучи.cmd"
$cmd = @"
@echo off
rem [DA_PORT] Запуск Dead Air с контролем кучи. Обычная игра — bin\xrEngine.exe, этот файл её не трогает.
rem
rem Что включено: освобождённая память травится байтом 0xDD и придерживается в карантине, поэтому
rem обращение к уже удалённому объекту падает СРАЗУ и с узнаваемым адресом 0xDDDDDDDD..., а не через
rem десять минут в непричастном месте.
rem
rem ⛔ Кадры тяжелее и памяти больше — это ожидаемо. По этой сборке НЕ судить о производительности.

set DA_HEAP_GUARD=1
set DA_HEAP_GUARD_MB=64

cd /d "%~dp0"
"%~dp0$DstName\xrEngine.exe" %*
"@
Set-Content -Path $runner -Value $cmd -Encoding OEM
Write-Host "  запуск: $runner"

Write-Host ""
Write-Host "Готово. Играть — двойным щелчком по 'ЗАПУСК_контроль_кучи.cmd' в корне игры."
Write-Host "В логе первой же строкой будет [DA_HEAP_GUARD] ВКЛЮЧЁН — по ней прогон и опознаётся."

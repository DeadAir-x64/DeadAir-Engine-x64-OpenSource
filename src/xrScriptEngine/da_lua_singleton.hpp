#pragma once

#include "lua.hpp"
#include <luabind/detail/push_to_lua.hpp>

// [DA_PORT] Одна обёртка Lua на объект-одиночку движка вместо новой на каждый вызов.
//
// Зачем. luabind на КАЖДЫЙ возврат указателя строит новый объект Lua — замер дал 128 байт на вызов
// (для сравнения: возврат числа или строки бесплатен). Скрипты мода дёргают одиночек постоянно:
// alife() около 870 раз в секунду, get_console() 166, system_ini() 150, get_hud() 53. Объект при
// этом каждый раз ОДИН И ТОТ ЖЕ, то есть весь этот мусор — чистые потери, около 160 КБ/сек.
//
// Что делает. Держит одну обёртку в реестре Lua и отдаёт её же.
//
// Почему это безопасно. Наивный кэш «на всю игру» был бы миной: часть одиночек пересоздаётся
// (симулятор ALife — при загрузке сейва, настройки — по reload_system_ini, интерфейс — со сменой
// сессии), и обёртка стала бы ссылкой на освобождённую память. Здесь кэш чинит себя сам сравнением
// указателей. Если новый объект ляжет по адресу старого, обёртка укажет на него же и останется
// верной — она хранит сырой указатель и ничем не владеет.
//
// Ссылку на реестр обязательно сбрасывать в script_register: он вызывается на каждое новое
// состояние Lua, а ссылка из прежнего состояния недействительна.
//
// ⛔ УСЛОВИЕ ПРИМЕНИМОСТИ, которое легко нарушить. Ссылка живёт в реестре КОНКРЕТНОГО состояния Lua,
// а поле здесь одно на всю программу. В игре состояний два: игровое (GEnv.ScriptEngine, ai_space.cpp)
// и отдельное у менеджера ресурсов рендера для шейдерных скриптов
// (Layers/xrRenderDX11/dx11ResourceManager_Scripting.cpp). Второе инициализируется СВОИМ экспортёром,
// то есть reset() для него не вызывается.
//
// Сейчас это безопасно, потому что шейдерный экспортёр регистрирует только классы рендера —
// ни alife, ни system_ini, ни get_console, ни get_hud там нет, и push() с тем состоянием не зовётся.
// Сопрограммы (lua_newthread) не мешают: они делят реестр с родителем.
//
// Значит: заворачивать сюда можно ТОЛЬКО то, что видно исключительно игровому состоянию. Если такая
// функция когда-нибудь понадобится шейдерным скриптам — здесь нужно хранить и сравнивать lua_State.
//
// Проверено наблюдением: при повторной загрузке сейва обёртка симулятора перестраивалась, адреса
// в логе разные — то есть подмена действительно ловится, а не «просто не случалась».
template <typename T>
class da_lua_singleton
{
    int m_ref{ LUA_NOREF };
    const void* m_ptr{ nullptr };

public:
    // Вызывать из script_register: прежнее состояние Lua уничтожено вместе со ссылкой.
    void reset()
    {
        m_ref = LUA_NOREF;
        m_ptr = nullptr;
    }

    int push(lua_State* L, T* current, pcstr name)
    {
        if (!current)
        {
            lua_pushnil(L);
            return 1;
        }

        if ((current != m_ptr) || (m_ref == LUA_NOREF))
        {
            if (m_ref != LUA_NOREF)
                luaL_unref(L, LUA_REGISTRYINDEX, m_ref);

            luabind::detail::push_to_lua(L, current);
            m_ref = luaL_ref(L, LUA_REGISTRYINDEX);
            m_ptr = current;

            // Событие редкое (старт и пересоздание объекта). Печатаем всегда: это доказательство,
            // что подмена ловится, а не что кэш «просто не ломался».
            Msg("~ [DA_LUA1] обёртка %s построена заново, адрес [%p]", name, (const void*)current);
        }

        lua_rawgeti(L, LUA_REGISTRYINDEX, m_ref);
        return 1;
    }
};

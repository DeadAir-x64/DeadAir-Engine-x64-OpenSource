#pragma once

// [DA_PORT] Полный перехват камеры из скрипта.
//
// Зачем отдельный эффектор, а не поворот штатной камеры. Штатные эффекторы ДОБАВЛЯЮТ поправку к
// тому, что уже посчитала камера актёра: тряска, отдача, покачивание при ходьбе. Здесь нужно
// обратное — на время подтягивания на уступ камера обязана стоять ровно там, куда её ставит скрипт,
// и никакие покачивания в неё вмешиваться не должны. Поэтому ProcessCam не читает info на входе, а
// перезаписывает положение и оси целиком.
//
// Сглаживание своё, скользящим средним, и оно НЕ ЗАВИСИТ ОТ ЧАСТОТЫ КАДРОВ. Наивное
// `current += k * (target - current)` каждый кадр даёт на 200 кадрах в секунду вдвое более резкое
// движение, чем на 100 — а камера при подтягивании как раз то место, где разница видна сразу.
// Поэтому в коэффициент входит длительность кадра.
//
// Приём и разбор — из Monolith (CFPCamEffector, автор demonized): исходники открыты, лицензия
// X-Ray/GSC требует сохранить уведомление, что и сделано этой строкой. Реализация переписана под
// наш CEffectorCam, у которого ProcessCam возвращает bool и есть готовые SetHudAffect/GetHudAffect.

#include "../xrEngine/Effector.h"

class CDaScriptCamEffector final : public CEffectorCam
{
public:
    CDaScriptCamEffector();

    // Целевое положение и углы, куда камера обязана прийти. Пишет скрипт, каждый кадр.
    Fvector m_position;
    Fvector m_hpb;

    // Текущее сглаженное состояние. Держим МАТРИЦЕЙ, а не углами: сглаживать углы нельзя — при
    // переходе через ±180° разность скачком меняет знак, и камера делает полный оборот вместо
    // короткого доворота. У осей матрицы этой особенности нет.
    Fmatrix m_camera;

    // 0 — сглаживание по умолчанию, 1 — без сглаживания (щёлкнуть в точку), больше — мягче.
    u32 m_smoothing;

    // Рисовать ли руки поверх перехваченной камеры.
    bool m_hud_enabled;

    // Эффектор живёт, пока его не снимут явно: у подтягивания нет заранее известной длительности.
    bool Valid() override { return true; }

    // ⚠️ Обязано быть true, иначе менеджер положит нас в КОНЕЦ очереди, и штатная камера отработает
    // после нас, затерев результат. См. CCameraManager::UpdateDeffered.
    bool AbsolutePositioning() override { return true; }

    bool ProcessCam(SCamEffectorInfo& info) override;

private:
    static void ema(Fvector& current, const Fvector& target, u32 steps);
};

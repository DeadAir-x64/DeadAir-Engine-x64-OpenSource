#pragma once

// [DA_PORT] Поиск утечки памяти по повторным загрузкам одного и того же сохранения.
//
// ЗАЧЕМ ОТДЕЛЬНЫЙ ИНСТРУМЕНТ. Замер по логу сессии показал рост 3.05 -> 5.25 ГБ за четыре загрузки
// уровня, шагом 0.65-0.80 ГБ. Само по себе это ничего не доказывает: Memory.mem_usage() возвращает
// PagefileUsage, то есть ЗАКОММИЧЕННУЮ память процесса, а не сумму живых аллокаций. В ней сидит и то,
// что приложение освободило, а аллокатор не вернул системе, — это норма, а не дефект. Значит решает
// не единичная разница, а ФОРМА КРИВОЙ на повторных загрузках ОДНОГО уровня:
//   вышло на плато (3.05 -> 3.4 -> 3.45) -- удержание памяти аллокатором, безвредно;
//   лезет ровным шагом (3.05 -> 3.8 -> 4.6) -- настоящая утечка на пути загрузки.
//
// И второе, ради чего это написано: мало знать, что течёт, — надо знать ГДЕ. Поэтому замер идёт не
// одной цифрой в конце, а отметками по фазам загрузки. Фаза, которая от прогона к прогону прибавляет
// одинаковый кусок, и есть виновник; остальные к третьей загрузке выходят на ноль.
//
// Пользоваться так: загрузить сохранение, потом ЕЩЁ ДВА раза загрузить его же, не выходя из игры,
// затем `da_mem_dump`. Таблица печатается и сама, в конце каждой загрузки.

// Начало нового прогона: сбрасывает счётчик фаз и запоминает исходную величину.
void DA_MemRunBegin(const char* what);

// Отметка фазы. Дёшево: одно обращение к счётчику памяти процесса.
void DA_MemMark(const char* label);

// Конец прогона: полный снимок по подсистемам и строка итога в лог.
void DA_MemRunEnd();

// Раз в кадр: досчитывает то, что в конце загрузки ещё не существовало (клиентские объекты),
// и ведёт авто-повтор (см. DA_MemTestStart).
void DA_MemTick();

// Автоматический прогон: перезагружает последнее сохранение нужное число раз подряд и печатает
// вывод. Ради него всё и затевалось — руками легко ошибиться, а ошибка обесценивает замер:
// перезапуск игры обнуляет накопленное, потому что таблица живёт в памяти процесса, и каждая
// сессия начинается с «прогон 1».
void DA_MemTestStart(int runs);

// Снимок посреди обычной игры, без перезагрузок (консольная команда da_mem_snap).
//
// Загрузочный протокол выше ловит не всё: из двух найденных утечек вторая — узлы xr_fixed_map в
// графе сцены рендера — текла ПОКАДРОВО, во время игры, и на трёх загрузках была почти не видна.
// За три загрузки набегает несколько тысяч кадров, за четверть часа игры — сотни тысяч; отсюда и
// «6 ГБ за десять минут» при почти чистой таблице загрузок.
//
// Протокол: `da_mem_probe 1`, `da_mem_heapwalk 1`, `da_mem_snap` -- играть 5-10 минут --
// `da_mem_snap` -- ещё столько же -- `da_mem_snap`, потом `da_mem_dump`. Решают колонки
// «блоков/1000 кадров» и таблица «какие блоки прибавились»: она называет РАЗМЕР структуры-виновника,
// а по размеру она находится в коде быстрее, чем любым чтением подряд.
void DA_MemSnap();

// Печать всей накопленной таблицы: фазы по вертикали, прогоны по горизонтали.
void DA_MemSizes();

void DA_MemDump();

// Забыть накопленное (консольная команда da_mem_reset).
void DA_MemReset();

// [DA_PORT] Отложенное выполнение консольной команды после загрузки уровня — см. .cpp.
// Нужно, чтобы воспроизводить сценарии («загрузил сейв, сбросил устройство») без рук.
void DA_AfterLoadArm(int frames, pcstr command);
void DA_AfterLoadTick();

// [DA_PORT] Один раз за сессию выполняет команду из `-da_cmd "<команда>"`. См. run_headless.ps1.
void DA_StartupCommandTick();

// [DA_PORT] Отключение сбора статики при обходе для ламп: r__light_skip_static.
//
//   0 - как было, статика собирается всегда;
//   1 - не собирать у ламп с годным кэшем статики (её всё равно не рисуют -- списки очищаются);
//   2 - ⚠️ НЕ СОБИРАТЬ НИ У КОГО. Тени от статики у некэшированных ламп пропадут -- это ЗАМЕР
//       потолка, а не режим игры: он отвечает, сколько всего стоит обход статики, и стоит ли
//       строить машинерию запоминания вердикта «пусто» для остальных восьмидесяти ламп.
//   3 - ⚠️ не запрашивать ДИНАМИКУ (пропадут тени от NPC и предметов) -- замер;
//   4 - ⚠️ ни статики, ни динамики: остаётся только обход порталов -- замер.
//
// РЕЗУЛЬТАТ РЕЖИМА 2: ожидание НЕ ИЗМЕНИЛОСЬ (1.2-1.4 мс что с ним, что без). То есть сбор статики
// не стоит ничего, и посылка «мы собираем списки, чтобы их выбросить» -- неверна. Кэш вердиктов,
// который под неё задумывался, не дал бы ничего. Режимы 3 и 4 добавлены, чтобы разделить два
// оставшихся кандидата: обход порталов и пространственный запрос динамики.
//
// Замер, ради которого всё: 96 обходов сцены за кадр, полезны 15, ожидание 1.25 мс -- девяносто
// процентов фазы света. Годный кэш при этом лишь у 16 ламп, поэтому режим 1 сам по себе снимет
// шестую часть, а режим 2 показывает верхнюю границу.

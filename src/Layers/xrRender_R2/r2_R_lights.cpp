// [DA_PORT] Общая выборка динамики на всю фазу света: r__light_dyn_shared (0 - как было, 1 - общая).
//
// Замер: 96 запросов SpatialSpace.q_frustum за кадр, по одному на лампу -- 1.1 мс из 1.25, то есть
// вся стоимость фазы. Отключение запроса роняет ожидание с 1.25 до 0.14 мс; отключение сбора
// статики не меняет ничего (проверено отдельно, r__light_skip_static 2).
//
// Схема: один запрос к дереву объектов по объёму, накрывающему ВСЕ теневые лампы, а дальше каждая
// лампа фильтрует готовый список своей пирамидой. Тест приёмки повторяет q_frustum дословно.
//
// Почему это верно: объект, попавший в пирамиду лампы, лежит внутри её сферы влияния, а объём
// запроса накрывает объединение этих сфер. Значит общий список -- надмножество любого частного, и
// состав теней не меняется. Обратное неверно: сузь объём -- и тени начнут пропадать выборочно,
// поэтому границы считаются по СФЕРАМ ламп, а не по их пирамидам.
int ps_da_light_dyn_shared = 1;

static xr_vector<ISpatial*> g_da_light_dyn;

// [DA_PORT] Разбор источников света: печать и поштучная изоляция.
//
// Повод: чёрный клин с ПРЯМЫМИ краями на земле вечером. Прямые края означают объём источника, а
// не тень предмета, и наш же комментарий в r2_R_render.cpp описывает этот симптом дословно —
// «свет ложится клином во весь экран, ровная диагональная граница». Там причиной были чужие
// матрицы у выброшенной из бюджета лампы; здесь бюджет не при чём (проверено: клин остаётся и
// без потолка, и с потолком в единицу), значит источник другой.
//
// Прибор даёт две вещи, которых не даёт ни один лог:
//   da_light_dump N — N кадров подряд печатает КАЖДЫЙ накопленный источник с его числами;
//   da_light_only N — накапливает ТОЛЬКО источник номер N, остальные пропускает.
// Второе и есть разделяющий опыт: номер, при котором клин остаётся один на экране, называет
// виновника точно, без рассуждений о том, что «похоже на фонарь».
//
// Нумерация сквозная за кадр и стабильна, пока не меняется состав света в кадре: порядок обхода
// списков фиксирован. Стоять при переборе нужно неподвижно.
// da_light_max N — накапливать только источники с номерами 1..N. Это и есть рабочая ручка: поштучная
// изоляция дефект НЕ воспроизводит (проверено — при любом одиночном номере клин пропадает), значит
// он рождается во взаимодействии источников, а такое ловится только границей «до какого номера ещё
// чисто». Признак монотонный, поэтому номер ищется делением пополам за шесть шагов, а не перебором.
int ps_da_light_dump = 0;
int ps_da_light_only = 0;
int ps_da_light_max = 0;

// [DA_PORT] Лечение чёрных клиньев от ламп: у объёма, задетого ближней плоскостью, трафаретная
// разметка отключается. Разбор — в r3_rendertarget_accum_spot.cpp. 0 возвращает прежнее поведение.
// ⛔ ПО УМОЛЧАНИЮ ВЫКЛЮЧЕНО. Первая версия этой правки отменяла разметку трафаретом и лампы
// засветили сквозь стены; вторая (снятие метки после источника) в игре ещё не подтверждена.
// Пока не подтверждена — в свет не вмешиваемся вовсе: при нуле обе функции накопления работают
// в точности как заводские, отличие ровно одно — возвращаемое значение enable_scissor теперь
// сохраняется в переменную, а не отбрасывается.
int ps_da_light_nearfix = 0;
static u32 g_da_light_idx = 0;

static pcstr da_light_type(u32 t)
{
    switch (t)
    {
    case IRender_Light::POINT: return "точка";
    case IRender_Light::SPOT: return "конус";
    case IRender_Light::OMNIPART: return "сектор";
    case IRender_Light::REFLECTED: return "отражён";
    default: return "?";
    }
}

// Возвращает false, если источник нужно пропустить (изоляция da_light_only).
static bool da_light_step(const light* L, pcstr where)
{
    ++g_da_light_idx;

    if (ps_da_light_dump > 0)
    {
        // Пересечение объёма источника с БЛИЖНЕЙ ПЛОСКОСТЬЮ камеры. Расчёт слово в слово тот же,
        // что в CRenderTarget::enable_scissor, только здесь он ничего не меняет, а печатается.
        //
        // Признак ключевой. Разметка объёма трафаретом идёт в два прохода: задние грани ставят
        // метку источника, передние возвращают её в 0x01. Когда камера внутри объёма (или он задет
        // ближней плоскостью), ПЕРЕДНИЕ грани обрезаются и второй проход не выполняется — метка
        // остаётся. Следующие источники проверяют трафарет как «ref <= значение», своя метка у них
        // больше, проверка не проходит, и они в эту область не светят. Получается ровно то, что
        // видно: тёмная область с прямыми краями по силуэту ЧУЖОГО объёма, и только там, где свет
        // ламп — единственный источник освещения, то есть ночью.
        //
        // Класс известный: это стандартная беда трафаретных объёмов в отложенном затенении, её
        // разбирают в статьях по deferred lighting (см. hacksoflife, gamedev.net). Штатное лечение —
        // при пересечении ближней плоскости не оптимизировать трафаретом вовсе.
        bool near_hit = false;
        {
            const Fmatrix& M = Device.mFullTransform;
            Fvector4 pl;
            pl.x = -(M._14 + M._13);
            pl.y = -(M._24 + M._23);
            pl.z = -(M._34 + M._33);
            pl.w = -(M._44 + M._43);
            const float denom = -1.0f / _sqrt(_sqr(pl.x) + _sqr(pl.y) + _sqr(pl.z));
            pl.mul(denom);
            Fplane P;
            P.n.set(pl.x, pl.y, pl.z);
            P.d = pl.w;
            near_hit = (P.classify(L->spatial.sphere.P) - L->spatial.sphere.R) <= 0.f;
        }

        Msg("~ [DA_LIGHT] #%02u %-14s %-7s тень %d | xyz %.1f %.1f %.1f | радиус %.1f | конус %.2f "
            "| цвет %.2f %.2f %.2f | атлас %ux%u+%u | не-снимать %d | БЛИЖНЯЯ ПЛОСКОСТЬ %d",
            g_da_light_idx, where, da_light_type(L->flags.type), L->flags.bShadow ? 1 : 0, L->position.x,
            L->position.y, L->position.z, L->range, L->cone, L->color.r, L->color.g, L->color.b, L->X.S.size,
            L->X.S.posX, L->X.S.posY, L->flags.bNeverDemote ? 1 : 0, near_hit ? 1 : 0);
    }

    if (ps_da_light_max > 0 && g_da_light_idx > u32(ps_da_light_max))
        return false;

    return !(ps_da_light_only > 0 && u32(ps_da_light_only) != g_da_light_idx);
}

void CRender::render_lights(light_Package& LP)
{
    g_da_light_idx = 0;

    // [DA_PORT] Разметка непокрытых кусков фазы -- разбор у g_da_lp_prep.
    const bool da_lp = ps_da_light_prof > 0;
    CTimer da_lp_timer;
    if (da_lp)
        da_lp_timer.Start();

    // [DA_PORT] Общая выборка динамики -- один раз на всю фазу. Разбор у ps_da_light_dyn_shared.
    g_da_light_dyn.clear();
    if (ps_da_light_dyn_shared && !LP.v_shadowed.empty())
    {
        Fbox bb;
        bb.invalidate();
        for (light* L : LP.v_shadowed)
        {
            Fvector r;
            r.set(L->spatial.sphere.R, L->spatial.sphere.R, L->spatial.sphere.R);
            Fvector lo, hi;
            lo.sub(L->spatial.sphere.P, r);
            hi.add(L->spatial.sphere.P, r);
            bb.modify(lo);
            bb.modify(hi);
        }
        // get_CD отдаёт ПОЛОВИНУ размера, а q_box строит куб как «центр ± это» (Fbox::setb) --
        //половины сходятся. Ошибись здесь вдвое, и объём стал бы вдвое меньше нужного: тени от
        // динамики начали бы пропадать у ламп по краям, и заметить это было бы тяжело.
        Fvector center, size;
        bb.get_CD(center, size);
        g_pGamePersistent->SpatialSpace.q_box(g_da_light_dyn, 0, STYPE_RENDERABLE, center, size);
    }

    if (da_lp)
    {
        g_da_lp_prep += da_lp_timer.GetElapsed_sec() * 1000.0;
        da_lp_timer.Start();
    }

    if (ps_da_light_prof > 0)
    {
        u32 free_ctx = 0;
        for (u32 i = 0; i < R__NUM_PARALLEL_CONTEXTS; ++i)
            if (!contexts_used.test(i))
                ++free_ctx;
        if (free_ctx > g_da_lp_free_ctx)
            g_da_lp_free_ctx = free_ctx;
    }

    ZoneScoped;

    //////////////////////////////////////////////////////////////////////////
    // Refactor order based on ability to pack shadow-maps
    // 1. calculate area + sort in descending order
    // const	u16		smap_unassigned		= u16(-1);
    {
        xr_vector<light*>& source = LP.v_shadowed;
        for (u32 it = 0; it < source.size(); it++)
        {
            light* L = source[it];
            L->vis_update();
            if (!L->vis.visible)
            {
                source.erase(source.begin() + it);
                it--;
            }
            else
            {
                LR.compute_xf_spot(L);
            }
        }
    }

    if (da_lp)
    {
        g_da_lp_vis += da_lp_timer.GetElapsed_sec() * 1000.0;
        da_lp_timer.Start();
    }

    // 2. refactor - infact we could go from the backside and sort in ascending order
    {
        xr_vector<light*>& source = LP.v_shadowed;
        xr_vector<light*> refactored;
        refactored.reserve(source.size());
        const size_t total = source.size();

        // [DA_PORT] Место в атласе закрепляется за источником, пока состав не изменился.
        //
        // ЗАЧЕМ. Ниже атлас теневых карт перепаковывается КАЖДЫЙ кадр: источники сортируются по
        // размеру и получают новые прямоугольники. Пока прямоугольник каждый кадр другой, содержимое
        // прошлого кадра переиспользовать нечего — а именно на этом стоит приём, которым индустрия
        // и убирает лишние прорисовки: статику рисуют в теневую карту один раз, дальше копируют
        // готовую глубину и дорисовывают поверх только то, что движется. Это фундамент под кэш, сам
        // по себе он кадр почти не ускоряет — экономит только сортировку и упаковку.
        //
        // КАК. Если набор источников и их размеры те же, что в прошлом кадре, упаковку не трогаем
        // вовсе: назначение (posX, posY, smap_ID) живёт в самом источнике и с прошлого кадра никуда
        // не делось. Достаточно восстановить ПОРЯДОК — от него зависит группировка по smap_ID в
        // цикле ниже.
        //
        // ⚠️ Подпись строится из указателей и размеров, отсортированных по указателю, то есть не
        // зависит от порядка. Указатели только СРАВНИВАЮТСЯ, разыменования мёртвого нет. Совпадение
        // подписи при изменившемся составе теоретически возможно (адрес переиспользован под другой
        // источник того же размера) — тогда чужой источник получит чужой прямоугольник, что даёт
        // artefact в тени, но не порчу памяти: прямоугольник это просто место в атласе.
        // ⛔ ПЕРВАЯ ПОПЫТКА БЫЛА НЕВЕРНОЙ, и её стоит помнить. Постоянство мест держалось на
        // подписи всего набора ламп: совпал состав и размеры — упаковку не трогаем. Замер: НОЛЬ
        // совпадений из 106. Состав меняется сам собой, видимость ламп мигает по запросам
        // перекрытия, и при сотне источников хотя бы один меняется каждый кадр. Требовать
        // совпадения всего набора — то же самое, что не кэшировать.
        //
        // Держим место ПОЛАМПОВО: лампа сохраняет свой прямоугольник, пока остаётся теневой и не
        // сменила размер ячейки, независимо от того, кто пришёл и ушёл рядом.
        for (u16 smap_ID = 0; refactored.size() != total; ++smap_ID)
        {
            LP_smap_pool.initialize(RImplementation.o.smapsize);

            // Сначала возвращаем на места тех, кто уже занимал ячейку в этом атласе и не менял
            // размер. Порядок важен: их прямоугольники резервируются ДО общей раскладки, иначе
            // первый подходящий займёт чужое место и постоянства не выйдет.
            if (ps_r__smap_stable_slots)
            {
                for (size_t test = 0; test < source.size(); ++test)
                {
                    light* L = source[test];
                    light::da_smap_cache& c = L->da_cache;
                    if (!c.valid || c.smap_ID != smap_ID || c.size != L->X.S.size)
                        continue;

                    SMAP_Rect R{};
                    Ivector2 at;
                    at.set(int(c.posX), int(c.posY));
                    if (!LP_smap_pool.push_at(R, L->X.S.size, at))
                        continue;

                    L->X.S.posX = R.min.x;
                    L->X.S.posY = R.min.y;
                    L->vis.smap_ID = smap_ID;
                    c.slot_kept = true;
                    refactored.push_back(L);
                    source.erase(source.begin() + test);
                    --test;
                }
            }

            std::sort(source.begin(), source.end(), [](light* l1, light* l2)
            {
                const u32 a0 = l1->X.S.size;
                const u32 a1 = l2->X.S.size;
                return a0 > a1; // reverse -> descending
            });
            for (size_t test = 0; test < source.size(); ++test)
            {
                light* L = source[test];
                SMAP_Rect R{};
                if (LP_smap_pool.push(R, L->X.S.size))
                {
                    // OK
                    L->X.S.posX = R.min.x;
                    L->X.S.posY = R.min.y;
                    L->vis.smap_ID = smap_ID;
                    L->da_cache.slot_kept = false; // разложена заново — прежнего содержимого нет
                    refactored.push_back(L);
                    source.erase(source.begin() + test);
                    --test;
                }
            }
        }

        // save (lights are popped from back)
        std::reverse(refactored.begin(), refactored.end());
        LP.v_shadowed = std::move(refactored);
    }

    auto& cmd_list = get_imm_context().cmd_list;
    Target->rt_smap_depth->set_slice_read(0);

    PIX_EVENT(SHADOWED_LIGHTS);

    //////////////////////////////////////////////////////////////////////////
    // sort lights by importance???
    // while (has_any_lights_that_cast_shadows) {
    //		if (has_point_shadowed)		->	generate point shadowmap
    //		if (has_spot_shadowed)		->	generate spot shadowmap
    //		switch-to-accumulator
    //		if (has_point_unshadowed)	-> 	accum point unshadowed
    //		if (has_spot_unshadowed)	-> 	accum spot unshadowed
    //		if (was_point_shadowed)		->	accum point shadowed
    //		if (was_spot_shadowed)		->	accum spot shadowed
    //	}
    //	if (left_some_lights_that_doesn't cast shadows)
    //		accumulate them
    if (da_lp)
        g_da_lp_pack += da_lp_timer.GetElapsed_sec() * 1000.0;

    static xr_vector<light*> L_spot_s;

    struct task_data_t
    {
        light* L{};
        Task* task{};
        u32 batch_id{};
        // [DA_PORT] Признаки «есть что рисовать» считаются ОДИН раз, в первом проходе.
        //
        // 🪤 Пересчитывать их во втором проходе нельзя: первый уже нарисовал статику и ОЧИСТИЛ её
        // списки. Лампа без динамики выглядела бы после этого как «рисовать нечего», не попадала бы
        // в L_spot_s и пропадала бы из освещения совсем.
        bool draw{};
        bool special{};
        // [DA_PORT] Статику этой лампе пришлось обновить в этом кадре. Копия атласа делается ОДИН
        // раз и ДО всех пачек, поэтому свежая статика в рабочий атлас этим кадром не попадёт —
        // её приходится нарисовать второй раз, обычным проходом.
        bool refreshed{};
        // [DA_PORT] Статику этой лампе не собирали (r__light_skip_static). Признак нужен ниже:
        // без списка статики `bN` окажется ложным, лампа сочтётся пустой и потеряет тень целиком,
        // хотя её статика лежит готовой в кэше и её надо лишь скопировать.
        bool static_skipped{};
    };
    static xr_vector<task_data_t> lights_queue{};
    lights_queue.reserve(R__NUM_SUN_CASCADES);

    const auto& flush_lights = [&]()
    {
        ZoneScopedN("flush lights");

        // [DA_PORT] Считаем ВОЛНЫ ожидания. Прибор показал, что 90% времени фазы света -- ожидание
        // задач построения списков. Версия: параллельных контекстов всего четыре, три из них
        // забирает солнце, и лампы прогоняются пачками по одной-две с ожиданием между ними. Если
        // волн окажется столько же, сколько ламп, версия верна; если одна-две -- неверна, и дело
        // просто в длительности самих задач.
        if (ps_da_light_prof > 0 && !lights_queue.empty())
            ++g_da_lp_waves;

        // [DA_PORT] Кэш теней ламп: статика и динамика рисуются раздельно.
        //
        // Порядок кадра (схема Unreal / Flax / Unity HDRP, у последней — дословно «блит из
        // кэшированного атласа в рабочий»):
        //   А. лампам с устаревшей статикой — нарисовать её в АТЛАС СТАТИКИ;
        //   Б. один раз скопировать весь атлас статики в рабочий;
        //   В. каждой лампе дорисовать в рабочем атласе ТОЛЬКО динамику.
        //
        // Состояние глубины в фазе В менять не надо: копия принесла настоящие значения глубины,
        // поэтому обычная проверка «ближе — рисуем» работает сама. В этом преимущество копии
        // глубины перед масками.
        const bool da_on = ps_r__smap_cache_lights && Target->da_smap_static_ok();
        // Ручку включили, а атласа нет — он выделяется при создании целей отрисовки. Молчать здесь
        // нельзя: со стороны это выглядит как «кэш включён и ничего не даёт».
        if (ps_r__smap_cache_lights && !da_on)
        {
            static bool da_told = false;
            if (!da_told)
            {
                da_told = true;
                Msg("! [DA] r__smap_cache_lights включён, но атлас статики не выделен — нужен vid_restart");
            }
        }

        // --- Фаза А: статика в свой атлас ---
        //
        // ⚠️ Ожидание задач стоит ЗДЕСЬ и только здесь: этот проход идёт первым, а ждать одну и ту
        // же задачу дважды нельзя. Второй проход ниже задач уже не касается.
        for (auto& d : lights_queue)
        {
            if (d.task)
            {
                if (ps_da_light_prof > 0)
                {
                    CTimer tw;
                    tw.Start();
                    TaskScheduler->Wait(*d.task);
                    g_da_lp_wait += tw.GetElapsed_sec() * 1000.0;
                }
                else
                    TaskScheduler->Wait(*d.task);
            }

            auto& dsgraph = get_context(d.batch_id);
            const bool bN = !dsgraph.mapNormalPasses[0][0].empty() || !dsgraph.mapMatrixPasses[0][0].empty();
            d.special = !dsgraph.mapNormalPasses[1][0].empty() || !dsgraph.mapMatrixPasses[1][0].empty() ||
                !dsgraph.mapSorted.empty();
            d.draw = bN || d.special || d.static_skipped;

            if (!da_on || !d.draw)
                continue;

            light* const L = d.L;
            if (da_smap_light_valid(L))
            {
                ++g_da_smap_static_hit;
                continue;
            }
            ++g_da_smap_static_draw;

            if (!da_static_slot_acquire(L))
                continue; // атлас статики полон — рисуем как раньше, целиком, в фазе В

            Target->phase_smap_spot_clear_rect(dsgraph.cmd_list, L, true);
            Target->phase_smap_spot(dsgraph.cmd_list, L, true);
            dsgraph.cmd_list.set_xform_world(Fidentity);
            dsgraph.cmd_list.set_xform_view(L->X.S.view);
            dsgraph.cmd_list.set_xform_project(L->X.S.project);
            // Только статика. Список НЕ сохраняем: в рабочий атлас она попадёт блитом, а не
            // повторной отрисовкой.
            dsgraph.render_graph(0, R_dsgraph_structure::da_graph_static_only);
            {
                extern int ps_r__grass_spot_shadows;
                if (ps_r__grass_spot_shadows && ps_r2_ls_flags.test(R2FLAG_SUN_DETAILS) && Details)
                    Details->Render(dsgraph.cmd_list);
            }
            da_smap_light_store(L);
            d.refreshed = true;
        }

        // ⛔ КОПИИ ЗДЕСЬ БЫТЬ НЕ ДОЛЖНО. Она делается один раз за кадр, до всех пачек, в
        // render_lights. Контекстов отрисовки четыре, а теневых ламп в баре шесть десятков, значит
        // flush_lights зовётся за кадр полтора десятка раз — и копия внутри него затирала бы
        // рабочий атлас вместе с динамикой, уже нарисованной предыдущими пачками. Сколько ламп
        // видно, столько и пачек, поэтому картинка менялась от шага игрока.

        // --- Фаза В: динамика поверх восстановленной статики ---
        for (auto& d : lights_queue)
        {
            light* const L = d.L;
            const u32 batch_id = d.batch_id;
            auto& dsgraph = get_context(batch_id);

            // Признаки взяты из фазы А, а не пересчитаны: см. task_data_t.
            const bool bSpecial = d.special;
            // [DA_PORT] Секундомер на всю отрисовку теневой карты лампы: очистка ячейки, копия
            // статики из кэша, сам проход геометрии. Взводится только по команде.
            CTimer t_smap;
            const bool prof = ps_da_light_prof > 0;
            if (prof && d.draw)
            {
                t_smap.Start();
                ++g_da_lp_lights;
            }
            if (prof && da_on && L->da_cache.valid && L->da_cache.st_owned)
            {
                ++g_da_lc_cached;
                if (d.special)
                    ++g_da_lc_cached_special;
            }
            if (prof)
            {
                const u32 sz = L->X.S.size;
                const double dist = double(Device.vCameraPosition.distance_to(L->position));
                if (d.draw)
                {
                    ++g_da_lc_drawn;
                    g_da_lc_drawn_dist += dist;
                    if (sz < g_da_lc_drawn_size_min) g_da_lc_drawn_size_min = sz;
                    if (sz > g_da_lc_drawn_size_max) g_da_lc_drawn_size_max = sz;
                }
                else
                {
                    ++g_da_lc_empty;
                    g_da_lc_empty_dist += dist;
                    if (sz < g_da_lc_empty_size_min) g_da_lc_empty_size_min = sz;
                    if (sz > g_da_lc_empty_size_max) g_da_lc_empty_size_max = sz;
                }
            }
            if (d.draw)
            {
                PIX_EVENT_CTX(dsgraph.cmd_list, SHADOWED_LIGHT);

                Stats.s_merged++;
                L_spot_s.push_back(L);
                // [DA_PORT] Ячейка чистится непосредственно перед тем, как в неё рисуют. Порядок
                // важен: заливка ставит свою область просмотра, а phase_smap_spot ставит её заново
                // под ту же ячейку — то есть заливка не может «утечь» на соседей.
                // ⛔ Кэшированной лампе ячейку чистить НЕЛЬЗЯ: в ней лежит восстановленная копией
                // статика, и заливка стёрла бы ровно то, ради чего всё затевалось.
                //
                // А вот ОБНОВЛЁННОЙ — чистить ОБЯЗАТЕЛЬНО, и это стоило нам утра отладки.
                // Копия начала пачки принесла в её ячейку СТАРУЮ статику. Дальше мы рисуем поверх
                // новую, но проверка глубины пропускает только то, что ближе: там, где старое
                // значение оказалось ближе нового, оно и остаётся. В ячейке — смесь двух положений
                // лампы. Раньше этого не было, потому что полная очистка атласа стирала всё; при
                // кэше её нет, и чистить приходится точечно.
                //
                // Заметно это ровно у качающихся ламп: чем сильнее лампа успела сдвинуться, тем
                // грязнее смесь. По счётчику таких было шесть из семнадцати.
                // При кэше рабочую ячейку чистим ВСЕГДА: копии атласа больше нет, значит в ней
                // лежит чужой мусор прошлого кадра. Дальше статику принесёт блит.
                if (da_on || ps_r__smap_clear_rect)
                    Target->phase_smap_spot_clear_rect(dsgraph.cmd_list, L);

                // Статика из своего атласа в рабочую ячейку. Получилось — рисовать её незачем.
                const bool da_blitted = da_on && L->da_cache.valid && L->da_cache.st_owned &&
                    Target->da_smap_blit_static(dsgraph.cmd_list, L);
                Target->phase_smap_spot(dsgraph.cmd_list, L);
                dsgraph.cmd_list.set_xform_world(Fidentity);
                dsgraph.cmd_list.set_xform_view(L->X.S.view);
                dsgraph.cmd_list.set_xform_project(L->X.S.project);
                // С кэшем — только динамика: статику принесла копия. Списки статики при этом всё
                // равно очищаются, иначе их элементы всплыли бы в следующем проходе.
                dsgraph.render_graph(0, da_blitted ? R_dsgraph_structure::da_graph_dynamic_only
                                                   : R_dsgraph_structure::da_graph_all);
                // [DA_PORT] Трава в теневой карте ПРОЖЕКТОРА — по отдельной ручке, по умолчанию нет.
                //
                // Строку сюда добавили мы, ради единообразия с основными проходами (r2_R_render.cpp:234
                // и :456). Цена выяснилась замером на Юпитере: при выключенном потолке теневых ламп
                // сцену рисуют 39 источников, и трава уезжает в КАЖДЫЙ из этих проходов — счётчик
                // dt_rend показывал 13.67 мс против 0.41 мс, когда теневых проходов не стало.
                //
                // Тень от травы, отброшенная настольной лампой, на картинке практически не читается,
                // а платим за неё сорок раз. Ручка оставлена: r__grass_spot_shadows 1 возвращает
                // прежнее поведение точь-в-точь.
                extern int ps_r__grass_spot_shadows;
                // С кэшем трава уходит в статику (фаза А): она от кадра к кадру не меняется.
                if (!da_on && ps_r__grass_spot_shadows && ps_r2_ls_flags.test(R2FLAG_SUN_DETAILS) && Details)
                    Details->Render(dsgraph.cmd_list);
                L->X.S.transluent = FALSE;
                if (bSpecial)
                {
                    L->X.S.transluent = TRUE;
                    Target->phase_smap_spot_tsh(dsgraph.cmd_list, L);
                    PIX_EVENT_CTX(dsgraph.cmd_list, SHADOWED_LIGHTS_RENDER_GRAPH);
                    dsgraph.render_graph(1); // normal level, secondary priority
                    PIX_EVENT_CTX(dsgraph.cmd_list, SHADOWED_LIGHTS_RENDER_SORTED);
                    dsgraph.render_sorted(); // strict-sorted geoms
                }
                if (prof)
                    g_da_lp_smap += t_smap.GetElapsed_sec() * 1000.0;
            }
            else
            {
                Stats.s_finalclip++;
            }

            L->svis[batch_id].end(); // NOTE(DX11): occqs are fetched here, this should be done on the imm context only
            RImplementation.release_context(batch_id);
        }

        lights_queue.clear();
    };

    while (!LP.v_shadowed.empty())
    {
        // if (has_spot_shadowed)
        Stats.s_used++;

        // generate spot shadowmap
        //
        // [DA_PORT] Очистка всего атласа или по ячейкам — см. phase_smap_spot_clear_rect.
        // Пока чистим целиком, кэшировать нечего: карта прошлого кадра стирается до того, как
        // её можно было бы переиспользовать. По ячейкам чистится ровно то, что тут же и
        // перерисовывается, а всё остальное в атласе остаётся нетронутым.
        // [DA_PORT] При кэше ламп полная очистка не нужна: рабочий атлас целиком восстанавливается
        // копией из атласа статики, а тот залит единицей при создании. Копия делает и очистку, и
        // восстановление разом.
        const bool da_cache_on = ps_r__smap_cache_lights && Target->da_smap_static_ok();
        // Первая заливка атласа статики: копия восстанавливает его ЦЕЛИКОМ, поэтому в ячейках без
        // кэшированной лампы иначе оказался бы мусор.
        if (da_cache_on && !Target->da_static_ready)
            Target->da_smap_static_clear(cmd_list);
        if (!ps_r__smap_clear_rect && !da_cache_on)
            Target->phase_smap_spot_clear(cmd_list);

        // ⛔ Копии всего атласа здесь БОЛЬШЕ НЕТ. Она требовала, чтобы раскладки двух атласов
        // совпадали, а они не совпадают принципиально: рабочий перепаковывается каждый кадр и
        // делится на пачки. Статика приходит в рабочий атлас ПОЛАМПОВО, блитом — см. da_smap_blit.
        xr_vector<light*>& source = LP.v_shadowed;
        light* L = source.back();
        const u16 sid = L->vis.smap_ID;
        while (true)
        {
            if (source.empty())
                break;
            L = source.back();
            if (L->vis.smap_ID != sid)
                break;

            const auto batch_id = alloc_context(false);
            if (batch_id == R_dsgraph_structure::INVALID_CONTEXT_ID)
            {
                if (ps_da_light_prof > 0)
                    ++g_da_lp_starved;
                VERIFY(!lights_queue.empty());
                flush_lights();
                continue;
            }

            source.pop_back();
            Lights_LastFrame.push_back(L);

            // [DA_PORT] Лампу БОЛЬШЕ НЕ ПРОПУСКАЕМ целиком, даже если её статика в кэше.
            //
            // Так было в первой версии, и это стоило дорого: пропущенная лампа не проходила
            // svis[batch_id].begin()/end(), то есть её запросы перекрытия не отправлялись и ответы
            // не забирались. Видимость лампы после этого решалась по устаревшим данным, лампа то
            // попадала в список, то нет — и это давало моргание не хуже, чем сам кэш.
            //
            // Теперь каждая лампа проходит полный путь, а экономится только отрисовка статики.

            task_data_t data{};
            data.batch_id = batch_id;
            data.L = L;

            const auto& calc_lights = [data]
            {
                ZoneScopedN("calc lights");
                auto& dsgraph = RImplementation.get_context(data.batch_id);
                {
                    auto* L = data.L;

                    L->svis[data.batch_id].begin();

                    dsgraph.o.phase = PHASE_SMAP;
                    dsgraph.r_pmask(true, RImplementation.o.Tshadows);
                    dsgraph.o.sector_id = L->spatial.sector_id;
                    dsgraph.o.view_pos = L->position;
                    dsgraph.o.xform = L->X.S.combine;
                    dsgraph.o.view_frustum.CreateFromMatrix(L->X.S.combine, FRUSTUM_P_ALL & (~FRUSTUM_P_NEAR));
                    // [DA_PORT] Разбор -- у ps_da_light_skip_static. Признак ставится ЗДЕСЬ, в
                    // настройке обхода, и он же запомнен в задании: ниже по нему решается, что
                    // лампу всё равно надо нарисовать (копией из кэша), несмотря на пустой список.
                    dsgraph.o.skip_static = data.static_skipped;
                    // Общий список действует только когда он собран: пустой -- значит выборка
                    // выключена или теневых ламп нет, и обход идёт к дереву как раньше.
                    dsgraph.o.dyn_source = (ps_da_light_dyn_shared && !g_da_light_dyn.empty())
                        ? &g_da_light_dyn : nullptr;
                    // Режимы 3 и 4 снимают запрос динамики: пустой spatial_types гасит его целиком
                    // (см. collect_dynamic_any в build_subspace).
                    const u32 da_types = dsgraph.o.spatial_types;
                    if (ps_da_light_skip_static >= 3)
                        dsgraph.o.spatial_types = 0;

                    dsgraph.build_subspace();

                    dsgraph.o.skip_static = false; // контекст вернётся в пул -- не оставляем следа
                    dsgraph.o.dyn_source = nullptr;
                    dsgraph.o.spatial_types = da_types;
                }
            };

            // calculate
            if (o.mt_calculate)
            {
                data.task = &TaskScheduler->AddTask(calc_lights);
            }
            else
            {
                calc_lights();
            }
            // [DA_PORT] Решаем ДО запуска задачи: собирать ли статику для этой лампы.
            // Режим 1 -- только там, где статика уже лежит в кэше и всё равно не будет нарисована.
            // Режим 2 -- у всех, это замер потолка (см. ps_da_light_skip_static).
            if (ps_da_light_skip_static == 2 || ps_da_light_skip_static == 4)
                data.static_skipped = true;
            else if (ps_da_light_skip_static == 1)
                data.static_skipped = ps_r__smap_cache_lights && Target->da_smap_static_ok() &&
                    L->da_cache.valid && L->da_cache.st_owned && L->da_cache.gen == Target->da_static_gen;

            lights_queue.emplace_back(data);
            if (ps_da_light_prof > 0)
                ++g_da_lp_queued;
            if (ps_da_light_prof > 0 && lights_queue.size() > g_da_lp_max_flight)
                g_da_lp_max_flight = u32(lights_queue.size());
        }
        flush_lights(); // in case if something left

        cmd_list.Invalidate();

        PIX_EVENT(UNSHADOWED_LIGHTS);

        //		switch-to-accumulator
        Target->phase_accumulator(cmd_list);

        PIX_EVENT(POINT_LIGHTS);

        //		if (has_point_unshadowed)	-> 	accum point unshadowed
        if (!LP.v_point.empty())
        {
            light* L2 = LP.v_point.back();
            LP.v_point.pop_back();
            L2->vis_update();
            if (L2->vis.visible)
            {
                if (da_light_step(L2, "точка"))
                    Target->accum_point(cmd_list, L2);
                render_indirect(L2);
            }
        }

        PIX_EVENT(SPOT_LIGHTS);

        //		if (has_spot_unshadowed)	-> 	accum spot unshadowed
        if (!LP.v_spot.empty())
        {
            light* L2 = LP.v_spot.back();
            LP.v_spot.pop_back();
            L2->vis_update();
            if (L2->vis.visible)
            {
                LR.compute_xf_spot(L2);
                const bool da_take = da_light_step(L2, "конус без тени");
                if (da_take)
                {
                    CTimer ta;
                    const bool pa = ps_da_light_prof > 0;
                    if (pa)
                        ta.Start();
                    Target->accum_spot(cmd_list, L2);
                    if (pa)
                    {
                        g_da_lp_accum += ta.GetElapsed_sec() * 1000.0;
                        ++g_da_lp_accums;
                    }
                }
                render_indirect(L2);
            }
        }

        PIX_EVENT(SPOT_LIGHTS_ACCUM_VOLUMETRIC);

        //		if (was_spot_shadowed)		->	accum spot shadowed
        if (!L_spot_s.empty())
        {
            PIX_EVENT(ACCUM_SPOT);
            for (light* p_light : L_spot_s)
            {
                if (da_light_step(p_light, "конус с тенью"))
                {
                    CTimer ta;
                    const bool pa = ps_da_light_prof > 0;
                    if (pa)
                        ta.Start();
                    Target->accum_spot(cmd_list, p_light);
                    if (pa)
                    {
                        g_da_lp_accum += ta.GetElapsed_sec() * 1000.0;
                        ++g_da_lp_accums;
                    }
                }
                render_indirect(p_light);
            }

            PIX_EVENT(ACCUM_VOLUMETRIC);
            if (RImplementation.o.advancedpp && ps_r2_ls_flags.is(R2FLAG_VOLUMETRIC_LIGHTS))
                for (light* p_light : L_spot_s)
                    Target->accum_volumetric(cmd_list, p_light);

            L_spot_s.clear();
        }
    }

    PIX_EVENT(POINT_LIGHTS_ACCUM);
    // Point lighting (unshadowed, if left)
    if (!LP.v_point.empty())
    {
        xr_vector<light*>& Lvec = LP.v_point;
        for (light* p_light : Lvec)
        {
            p_light->vis_update();
            if (p_light->vis.visible)
            {
                render_indirect(p_light);
                if (da_light_step(p_light, "точка (остаток)"))
                    Target->accum_point(cmd_list, p_light);
            }
        }
        Lvec.clear();
    }

    PIX_EVENT(SPOT_LIGHTS_ACCUM);
    // Spot lighting (unshadowed, if left)
    if (!LP.v_spot.empty())
    {
        xr_vector<light*>& Lvec = LP.v_spot;
        for (light* p_light : Lvec)
        {
            p_light->vis_update();
            if (p_light->vis.visible)
            {
                LR.compute_xf_spot(p_light);
                render_indirect(p_light);
                if (da_light_step(p_light, "конус (остаток)"))
                {
                    CTimer ta;
                    const bool pa = ps_da_light_prof > 0;
                    if (pa)
                        ta.Start();
                    Target->accum_spot(cmd_list, p_light);
                    if (pa)
                    {
                        g_da_lp_accum += ta.GetElapsed_sec() * 1000.0;
                        ++g_da_lp_accums;
                    }
                }
            }
        }
        Lvec.clear();
    }

    if (ps_da_light_dump > 0)
    {
        Msg("~ [DA_LIGHT] ---- кадр %u закончен, источников накоплено: %u ----", Device.dwFrame, g_da_light_idx);
        --ps_da_light_dump;
    }
}

void CRender::render_indirect(light* L) const
{
    if (!ps_r2_ls_flags.test(R2FLAG_GI))
        return;

    auto& cmd_list = RImplementation.get_imm_context().cmd_list;

    light LIGEN;
    LIGEN.set_type(IRender_Light::REFLECTED);
    LIGEN.set_shadow(false);
    LIGEN.set_cone(PI_DIV_2 * 2.f);

    const xr_vector<light_indirect>& Lvec = L->indirect;
    if (Lvec.empty())
        return;
    const float LE = L->color.intensity();
    for (auto& LI : Lvec)
    {
        // energy and color
        const float LIE = LE * LI.E;
        if (LIE < ps_r2_GI_clip)
            continue;

        Fvector T{ L->color.r, L->color.g, L->color.b };
        T.mul(LI.E);
        LIGEN.set_color(T.x, T.y, T.z);

        // geometric
        Fvector L_up{ 0, 1, 0 }, L_right;
        if (_abs(L_up.dotproduct(LI.D)) > .99f)
            L_up = { 0, 0, 1 };

        L_right.crossproduct(L_up, LI.D).normalize();
        LIGEN.spatial.sector_id = LI.S;
        LIGEN.set_position(LI.P);
        LIGEN.set_rotation(LI.D, L_right);

        // range
        // dist^2 / range^2 = A - has infinity number of solutions
        // approximate energy by linear fallof Emax / (1 + x) = Emin
        const float Emax = LIE;
        const float Emin = 1.f / 255.f;
        const float x = (Emax - Emin) / Emin;
        if (x < 0.1f)
            continue;
        LIGEN.set_range(x);

        Target->accum_reflected(cmd_list, &LIGEN);
    }
}

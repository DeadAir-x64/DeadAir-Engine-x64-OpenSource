// [DA_PORT] Почему кэш лампы не сработал. Счётчик «сколько раз не сработало» бесполезен: он не
// говорит, чинить нечего или чинить нужно. Считаем ПРИЧИНЫ — как с потолком поиска пути.
enum da_smap_reject { DA_SR_OFF, DA_SR_SLOTS, DA_SR_FIRST, DA_SR_TIME, DA_SR_PLACE, DA_SR_MOVED,
                      DA_SR_GEN, DA_SR_COUNT };
u32 g_da_smap_reject[DA_SR_COUNT] = {};
u32 g_da_smap_static_hit = 0;  // статику взяли из атласа
u32 g_da_smap_static_draw = 0; // статику пришлось нарисовать

static u32 g_da_static_serial = 0;

// [DA_PORT] ПОСТОЯННАЯ раскладка атласа статики — своя, независимая от рабочей.
//
// ⛔ Это и есть то, чего не хватало пяти предыдущим попыткам. Рабочий атлас перепаковывается каждый
// кадр и делится на пачки, поэтому повторить его раскладку во втором атласе НЕЛЬЗЯ. В HDRP у
// кэшированных теней свой атлас: источник получает место при первой отрисовке и держит его, а не
// влезший просто не кэшируется. Здесь так же.
static SMAP_Allocator g_da_static_alloc;
static u32 g_da_static_alloc_gen = 0;
static u32 g_da_defrag_frame = 0; // не перекладывать атлас дважды за кадр

static bool da_static_slot_acquire(light* L)
{
    CRenderTarget* T = RImplementation.Target;
    if (g_da_static_alloc_gen != T->da_static_gen)
    {
        g_da_static_alloc.initialize(T->rt_da_smap_static->dwWidth);
        g_da_static_alloc_gen = T->da_static_gen;
    }

    light::da_smap_cache& c = L->da_cache;
    if (c.st_owned && c.gen == T->da_static_gen && c.st_size == L->X.S.size)
        return true; // место уже наше и подходит по размеру

    SMAP_Rect R;
    if (!g_da_static_alloc.push(R, L->X.S.size))
    {
        // [DA_PORT] Место кончилось — ДЕФРАГМЕНТАЦИЯ, а не отказ навсегда.
        //
        // Так же поступает HDRP: у них вытеснение идёт по событиям (источник уничтожен или
        // выключен), а на случай «разместились неудачно и новому места нет» есть отдельная функция,
        // принудительно перекладывающая тени внутри атласа.
        //
        // ⭐ «Ушёл из кадра» поводом для вытеснения НЕ является — ни у них, ни у нас. Лампа держит
        // место, пока жива, и когда игрок возвращается, тень уже готова. Вытеснение по давности
        // (LRU) именно это свойство и сломало бы.
        //
        // Нам такой приём подходит вдвойне: не нужен ни список свободных прямоугольников, ни
        // отслеживание уничтожения ламп. Перекладываем всё и объявляем содержимое недействительным
        // поднятием поколения — каждая лампа возьмёт новое место и перерисует статику.
        //
        // ⚠️ Не чаще одного раза за кадр: иначе первая же не поместившаяся лампа перекладывала бы
        // атлас, следующая — снова, и так по кругу, без единого кэшированного кадра.
        if (g_da_defrag_frame != Device.dwFrame)
        {
            g_da_defrag_frame = Device.dwFrame;
            g_da_static_alloc.initialize(T->rt_da_smap_static->dwWidth);
            T->da_static_gen = ++g_da_static_serial + 1000000u; // поколение вперёд: всё прежнее негодно
            g_da_static_alloc_gen = T->da_static_gen;

            static u32 da_defrags = 0;
            ++da_defrags;
            if (da_defrags <= 5 || (da_defrags % 100) == 0)
                Msg("* [DA] атлас статики переложен: не нашлось места под ячейку %u (раз %u). "
                    "Если это повторяется часто — мал r__smap_cache_atlas",
                    L->X.S.size, da_defrags);
        }
        return false; // в этом кадре лампа рисуется как обычно, место получит в следующем
    }

    c.st_posX = u32(R.min.x);
    c.st_posY = u32(R.min.y);
    c.st_size = L->X.S.size;
    c.st_owned = true;
    return true;
}

// [DA_PORT] Годна ли СТАТИЧЕСКАЯ половина карты этой лампы, лежащая в атласе статики.
//
// Кэшируется только статика: она живёт в отдельном атласе, на закреплённом за лампой месте, и
// каждый кадр переносится оттуда в рабочий атлас блитом. Динамика рисуется заново поверх, поэтому
// «протухнуть» кэш не может — угадывать, шевельнулось ли что-то в объёме лампы, больше не нужно.
//
// Проверяется ровно то, от чего зависит СТАТИЧЕСКАЯ картинка:
//   1. атлас статики не пересоздавался (поколение);
//   2. статика в него записана;
//   3. место за лампой закреплено и размер ячейки прежний;
//   4. лампа не сдвинулась, не повернулась, не сменила радиус;
//   5. не истёк предельный возраст, если он задан, — это страховка, а не механизм.
//
// 🪤 Здесь ДВАЖДЫ оставались условия прежней схемы — slot_kept и пересечение прямоугольников. Оба
// говорили про место в РАБОЧЕМ атласе, которое меняется каждый кадр, и оба молча обнуляли кэш при
// полностью исправной механике. Нашлись только счётчиком причин. Любое условие здесь обязано
// объяснять, к какому из ДВУХ атласов оно относится.
static bool da_smap_light_valid(light* L)
{
    if (!ps_r__smap_cache_lights || !RImplementation.Target->da_smap_static_ok())
    {
        ++g_da_smap_reject[DA_SR_OFF];
        return false;
    }
    // Атлас статики мог быть пересоздан (vid_restart, смена разрешения). Объекты ламп это
    // переживают, поэтому без поколения кэш уверенно показывал бы содержимое чужого атласа.
    if (L->da_cache.gen != RImplementation.Target->da_static_gen)
    {
        ++g_da_smap_reject[DA_SR_GEN];
        return false;
    }
    // ⛔ Проверки slot_kept здесь БОЛЬШЕ НЕТ, и это следствие переделки архитектуры.
    //
    // Она означала «лампа сохранила место в РАБОЧЕМ атласе» и была обязательна, пока статика лежала
    // там же. Теперь статика в своём атласе, на своём постоянном месте, а рабочее назначение
    // меняется каждый кадр и на кэш не влияет никак.
    //
    // 🪤 Условие пережило переделку и молча отсекало 15 ламп из 21 — кэш давал ровно 0% попаданий
    // при полностью исправной механике. Нашлось только счётчиком причин: «слоты 15» в отчёте.
    // Урок: меняя схему, проверять НЕ ТОЛЬКО то, что добавил, но и то, что осталось от прежней.

    light::da_smap_cache& c = L->da_cache;
    if (!c.valid)
    {
        ++g_da_smap_reject[DA_SR_FIRST];
        return false;
    }

    // Предельный возраст статики — страховка, а не механизм. 0 означает «без ограничения»:
    // в промышленной схеме сброс идёт по событиям, таймер там не нужен.
    if (ps_r__smap_cache_lights_ms && Device.dwTimeGlobal - c.time_ms >= u32(ps_r__smap_cache_lights_ms))
    {
        ++g_da_smap_reject[DA_SR_TIME];
        return false;
    }

    // ⛔ Место в РАБОЧЕМ атласе здесь больше не проверяется, и это принципиально: оно меняется
    // каждый кадр, а статика лежит в своём атласе, на своём постоянном месте. Значение имеет только
    // размер: карта нарисована под него, и при другом разрешении её пришлось бы масштабировать.
    if (!c.st_owned || c.st_size != L->X.S.size)
    {
        ++g_da_smap_reject[DA_SR_PLACE];
        return false;
    }

    if (!c.pos.similar(L->position, EPS_L) || !c.dir.similar(L->direction, EPS_L) ||
        !fsimilar(c.range, L->range, EPS_L))
    {
        ++g_da_smap_reject[DA_SR_MOVED];
        return false;
    }

    // ⛔ Проверки пересечения прямоугольников здесь ТОЖЕ больше нет — второй остаток прежней схемы.
    //
    // Она сравнивала прямоугольники в РАБОЧЕМ атласе, а те меняются каждый кадр, поэтому отсекала
    // вообще всё: 36 ламп из 36. При постоянной раскладке атласа статики пересечений не бывает по
    // построению — распределитель их не допускает, — и проверять нечего.
    //
    // 🪤 Два остатка подряд, и оба нашлись только счётчиком причин. Меняя архитектуру, надо
    // перечитывать ВСЕ условия старой, а не убирать их по одному по мере того, как они выстрелят.

    // ⛔ Отпечатка движущихся объектов здесь БОЛЬШЕ НЕТ — и это вся суть переделки.
    //
    // Раньше кэшировалась карта целиком, поэтому приходилось угадывать, шевельнулось ли что-то в
    // объёме лампы. Догадка неточна по определению: слишком чуткая — кэш не срабатывает никогда,
    // слишком грубая — тень отстаёт от жизни. Отсюда и моргание. Теперь кэшируется только статика,
    // динамика рисуется каждый кадр поверх, и угадывать нечего.
    return true;
}

// [DA_PORT] Запомнить, с чем нарисована карта этой лампы. Зовётся сразу после отрисовки.
static void da_smap_light_store(light* L)
{
    light::da_smap_cache& c = L->da_cache;
    c.pos = L->position;
    c.dir = L->direction;
    c.range = L->range;
    c.posX = L->X.S.posX;
    c.posY = L->X.S.posY;
    c.size = L->X.S.size;
    c.smap_ID = L->vis.smap_ID;
    c.time_ms = Device.dwTimeGlobal;
    c.gen = RImplementation.Target->da_static_gen;
    c.serial = ++g_da_static_serial;
    c.valid = true;
}


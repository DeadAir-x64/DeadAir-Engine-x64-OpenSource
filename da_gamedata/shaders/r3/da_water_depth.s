-- [DA_PORT] Глубина воды для НАШЕЙ темпоралки: отдельный проход по её же геометрии.
--
-- Зачем. Наша TAA не читает буфер скоростей вовсе - она перепроецирует пиксель из его позиции в
-- G-буфере (см. da_taa.ps, s_position.z). Вода рисуется прямым проходом после G-буфера и позиции
-- не пишет, поэтому на пикселях воды там лежит глубина ДНА: история берётся не оттуда, где вода,
-- и поверхность мигает при каждом повороте камеры.
--
-- Это ровно та же беда, что была у апскейлеров, и лечится она тем же приёмом. Разница только в
-- том, ЧТО читает потребитель: апскейлер - вектор (da_water_velocity), наша темпоралка - глубину.
-- Поэтому вершинная половина общая, своя только пиксельная.
--
-- Смешивание выключено: со смешиванием глубина усреднилась бы с дном. Запись глубины тоже
-- выключена - проход ничего не решает о видимости, он заполняет позицию там, где вода уже
-- нарисована. Сравнение ослаблено до "меньше ИЛИ РАВНО" по той же причине, что и у векторов: на
-- болоте вода лежит почти вплотную ко дну, и строгое "меньше" даёт дыры.

function normal (shader, t_base, t_second, t_detail)
	shader	:begin		("da_water_velocity","da_water_depth")
			:blend		(false, blend.one, blend.zero)
			:zb			(true, false)
			:dx10zfunc	(cmp_func.lessequal)
			:fog		(false)
end

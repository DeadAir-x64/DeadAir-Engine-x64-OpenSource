-- [DA_PORT] Перенос кэшированной статики лампы в рабочий теневой атлас. См. da_smap_blit.ps.

function normal (shader, t_base, t_second, t_detail)
	-- da_fullscreen, а не заготовка из движка: заготовки объявляют разметку вершин, не совпадающую
	-- с FVF::F_TL, которой рисуется g_combine, а несовпадение заставляет DirectX МОЛЧА отбросить
	-- отрисовку. Этот урок нам уже стоил часов (см. комментарий в da_fullscreen.vs).
	shader:begin	("da_fullscreen","da_smap_blit")
			: fog	(false)
			-- Глубину пишем безусловно: сравнение выключено, запись включена. Проход и существует
			-- ровно ради того, чтобы положить в ячейку чужие значения глубины.
			: zb 	(false,true)
			-- Цвет не трогаем вовсе: цель этого прохода — только буфер глубины.
			: color_write_enable (false,false,false,false)

	shader:dx10texture	("s_dastatic", "$user$da_smap_static")

	-- Точечная выборка: значения глубины интерполировать нельзя, а Load её и не использует —
	-- сэмплер объявлен только затем, чтобы объявление текстуры было полным.
	shader:dx10sampler	("smp_nofilter")
end

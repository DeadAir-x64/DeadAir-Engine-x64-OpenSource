-- [DA_PORT] Векторы движения для воды: отдельный проход по её же геометрии.
--
-- Почему отдельным проходом, а не вторым выходом основного шейдера воды: вода рисуется со
-- смешиванием (srcalpha/invsrcalpha), а раздельного смешивания по целям бэкенд не умеет —
-- IndependentBlendEnable выключен, все цели наследуют настройки первой. Второй выход тогда
-- смешался бы с тем, что уже лежит в буфере скоростей, и вектор получился бы средним между водой и
-- дном. Здесь смешивание выключено полностью.
--
-- Запись глубины тоже выключена: этот проход ничего не решает о видимости, он только заполняет
-- вектор там, где вода уже нарисована.

function normal (shader, t_base, t_second, t_detail)
	shader	:begin		("da_water_velocity","da_water_velocity")
			:blend		(false, blend.one, blend.zero)
			:zb			(true, false)

			-- [DA_PORT] Сравнение глубины ослаблено до "меньше ИЛИ РАВНО".
			--
			-- С обычным "меньше" вектора на воде выходили ДЫРЯВЫМИ, и это видно в буфере скоростей
			-- (r__motion_vectors 2): вместо ровного поля — рваная мешанина, где чёрное значит
			-- "вектора нет". Апскейлер на таких пикселях берёт историю из того же места экрана,
			-- и вся вода превращается в кашу.
			--
			-- Причина в том, что на болоте вода лежит почти вплотную ко дну. Разница глубин
			-- мизерная, тест срабатывает по пикселям через раз — то же самое z-fighting, только
			-- проявляется не мерцанием цвета, а пропусками в буфере скоростей.
			--
			-- Пиксели, где вода реально перекрыта (кусты, камни), это не задевает: там глубина
			-- геометрии заметно меньше, и тест по-прежнему отбрасывает.
			:dx10zfunc	(cmp_func.lessequal)
			:fog		(false)
end

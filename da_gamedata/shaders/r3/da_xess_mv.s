-- [DA_PORT] Копия буфера скоростей со знаком, который ждёт XeSS.
--
-- Зачем отдельный проход. Наш буфер хранит вектор, ПЕРЕВЁРНУТЫЙ относительно NDC: это видно по
-- множителям, с которыми его читают все остальные — FSR 2, FSR 3 и DLSS берут его как
-- (x * -W/2, y * +H/2), то есть переворачивают X и не переворачивают Y, хотя честный перевод
-- NDC->пиксели требует ровно обратного. Знаки там выставлены НАБЛЮДЕНИЕМ в игре и трогать их нельзя.
--
-- А у XeSS такого рычага нет вовсе: с флагом USE_NDC_VELOCITY он берёт буфер как есть, и никакого
-- параметра масштаба в xess_d3d11_execute_params_t не предусмотрено. Поэтому он один получал вектора
-- задом наперёд и мазал при движении камеры, пока FSR 3 на той же машине работал безупречно.
--
-- Отсюда и решение: не трогать общий буфер (на нём сидят три доведённых до ума потребителя), а
-- положить XeSS его собственную копию. Проход идёт только когда XeSS активен.
--
-- ✅ Подтверждено в игре на Intel Arc B580: верный вариант — перевернуть ОБЕ оси
-- (r__xess_mv_sign 1). При перевороте одной оси размазывает сильнее прежнего.

function normal (shader, t_base, t_second, t_detail)
	-- da_fullscreen, не стоковая заглушка: у тех разметка вершин не совпадает с FVF::F_TL, которым
	-- рисуется квад, а несовпадение DirectX отбрасывает молча.
	shader:begin	("da_fullscreen","da_xess_mv")
			: fog	(false)
			: zb 	(false,false)

	shader:dx10texture	("s_velocity", "$user$velocity")

	-- Точечная выборка: значение в пикселе и есть ответ, интерполировать нечего.
	shader:dx10sampler	("smp_nofilter")
end

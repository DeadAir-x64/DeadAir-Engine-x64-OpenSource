// [DA_PORT] ============ НАСТРОЙКИ ВОДЫ ============================================================
//
// Формат заимствован у Screen Space Shaders для Anomaly: у них каждая фича держит свои крутилки в
// отдельном settings_screenspace_*.h, а логика шейдера остаётся чистой. Смысл в том, что настройки
// правит человек, а логику — программист, и смешивать их в одном файле значит заставлять первого
// лазить по второму.
//
// Всё, что здесь лежит, применяется БЕЗ пересборки движка: правишь число, удаляешь кэш шейдеров
// (appdata\shaders_cache_oxr), запускаешь игру.
//
// Подключается из water.ps и water_green.ps.
#ifndef SETTINGS_DA_WATER_H
#define SETTINGS_DA_WATER_H

// [DA_PORT] ---- Water look ------------------------------------------------------------------------
// Three things were missing next to what a modern X-Ray water shader does, and all three are what makes
// water read as expensive rather than as a tinted mirror.

// 1. Depth colour. The stock shader tints deep water with a flat grey (0.1, 0.1, 0.1). Real water is a
//    coloured filter: red is absorbed within about a metre, green survives several, blue furthest — so
//    the colour SHIFTS with depth instead of just darkening. Shallow tint is what a boot-deep puddle
//    over silt looks like; deep tint is the standing water in the Zone, green-black rather than blue.
#define WATER_TINT_SHALLOW	float3(0.10, 0.16, 0.15)
#define WATER_TINT_DEEP		float3(0.035, 0.085, 0.095)
#define WATER_TINT_FALLOFF	0.26	// larger = the deep colour takes over closer to the shore

// 2. Shoreline foam. Where the bed comes up to meet the surface there is always broken water. Its
//    absence is the single most obvious tell that a water plane is just a plane.
// Narrow, because the shores here are shallow-sloped: a wide band spread over many metres of ground
// stops reading as a shoreline and just hazes the whole surface.
#define WATER_FOAM_WIDTH	0.25	// metres of depth over which the foam fades out
#define WATER_FOAM_STRENGTH	0.90
#define WATER_FOAM_COLOR	float3(0.62, 0.62, 0.58)

// [DA_PORT] 3. Плавающий сор на поверхности: ближняя и дальняя границы окна глубины (метры) и сила.
// Ближе NEAR сора нет — там уже берег; дальше FAR нет тоже — там глубина, сор до берега не донесло.
// [DA_PORT] ---- РЯСКА на стоячей воде ----
// Зелёный ковёр на поверхности. Заменила плавающую листву: та читалась мусором В воде, а не на ней.
// От текстуры берётся только альфа как зерно, цвет задаётся здесь.
#define WATER_RYASKA_SCALE	4.50	// множитель к мировой развёртке: больше — зерно мельче
#define WATER_RYASKA_PATCH	0.10	// частота пятен: меньше — пятна крупнее
#define WATER_RYASKA_COVER	0.55	// доля поверхности под ряской, 0..1
#define WATER_RYASKA_CUT	0.38	// порог зерна: выше — тонкие веточки отсекаются, остаются пятна
#define WATER_RYASKA_SHARP	3.5	// резкость зерна
#define WATER_RYASKA_STRENGTH	1.00	// плотность ковра
#define WATER_RYASKA_NEAR	0.05	// метры: мельче — ряски нет, там берег
#define WATER_RYASKA_FAR	2.50	// глубже — ряски нет, там открытая вода
#define WATER_RYASKA_COLOR	float3(0.20, 0.30, 0.12)	// болотный; 0.26/0.38 было кислотно, 0.17/0.23 не видно

// Дрейф ряски, МЕТРЫ В СЕКУНДУ. Привязка к миру убрала «волна идёт по листу», но заодно сделала ковёр
// мёртвым: он стоял как нарисованный. Ряску таскает течением и ветром, только очень медленно —
// сантиметры в секунду. Плюс лёгкое поперечное качание, иначе движение читается конвейерной лентой.
//
// ⚠️ Здесь timers.x можно прибавлять напрямую, в отличие от ряби в da_puddles.h: там он шёл в
// хеш-функцию с frac(), и на больших числах рисунок вырождался. Тут это выборка ТЕКСТУРЫ — она к
// величине UV нечувствительна, аппаратная фильтрация работает одинаково и на сотнях единиц.
// [DA_PORT] Амплитуда волны: во сколько раз ослабить возмущение нормали от бегущих карт нормалей.
//
// 1.0 — как было. Меньше — поверхность спокойнее: наклоны мельче, блик и отражение меньше «ходят».
// На болоте это по существу: там стоячая вода, ей положено быть почти гладкой, а рябь — от ветра, а
// не от течения.
//
// ⚠️ Действует на ВСЮ воду. Болота отрисовываются шейдером ПРОТОЧНОЙ воды (effects\water), потому что
// шейдер прописан в геометрии уровня — переключить его на стоячий (effects_waterstuden) из loose-файлов
// нельзя. Поэтому тише станут и реки. Отдельно для болот — только правкой уровня или подменой имени
// шейдера в движке.
#define WATER_WAVE_AMP		0.55

// [DA_PORT] ---- Дальняя вода: гашение ряби с расстоянием ------------------------------------------
//
// Жалоба: при апскейлерах далёкая вода мерцает. Причина не в апскейлере, он её только проявляет.
//
// Нормаль воды складывается из двух бегущих карт и идёт в reflect(), а луч отражения выбирает цвет
// из кубмапы. Вдали один пиксель накрывает много волн, но нормаль берётся ОДНА — какая попала под
// центр выборки. Между кадрами она меняется, луч разворачивает, и цвет пикселя скачет целиком.
// Апскейлер бьёт по этому трижды: кадр рисуется в 60-70% разрешения (пиксель ещё крупнее), сдвиг
// мипов отрицательный (карта нормалей резче), и джиттер каждый кадр двигает точку выборки.
//
// Мип-фильтрацией это не лечится в принципе: среднее нормалей не равно среднему отражений. Поэтому
// амплитуда гасится явно — с расстояния рябь и должна усредняться в зеркало.
//
// Вблизи (до START) не меняется ничего.
#define WATER_FAR_START		25.0	// метры: докуда вода остаётся ровно такой, как была
#define WATER_FAR_END		120.0	// метры: где гашение достигает предела
#define WATER_FAR_AMP		0.12	// остаточная доля ряби вдали; 0 = зеркало

// [DA_PORT] ---- Потолок яркости отражения: против «огоньков на ёлке» -----------------------------
//
// Симптом: вблизи вода вспыхивает одиночными точками, каждый кадр в новых местах. Причина не в
// апскейлере — он только проявляет. Нормаль поверхности складывается из двух бегущих карт, по ней
// reflect() разворачивает луч, и цвет берётся из отражения. Один пиксель вблизи накрывает несколько
// волн, а нормаль берётся ОДНА — та, что попала под центр выборки. Между кадрами она меняется, луч
// уходит в другую часть неба, и если попадает на солнце — пиксель вспыхивает в разы ярче соседей.
//
// Усреднением это не лечится: среднее нормалей не равно среднему отражений. Зато лечится потолком —
// приём известен как подавление «светлячков». Ограничивается только ВЫБРОС: пиксель, который ярче
// порога, притягивается к нему, остальные не трогаются вовсе. Блик на воде остаётся, пропадает
// только его способность скакать на порядок между кадрами.
//
// Чтобы выключить — закомментируйте строку ниже. Через значение это сделать нельзя: препроцессор
// HLSL не сравнивает дробные числа в #if, поэтому переключатель именно #ifdef.
// Больше значение = мягче отсечка; 1.0 уже заметно приглушает солнечную дорожку.
#define WATER_REFL_CLAMP	1.25

// [DA_PORT] ---- Экранные отражения только вблизи --------------------------------------------------
//
// Дальше WATER_SSR_END отражение берётся из кубмапы неба, а луч по экрану не пускается вовсе.
//
// Две причины, и обе настоящие. Первая: вдали SSR физически не может быть верным — луч уходит за
// край экрана, отражать нечего, и результат держится на затухании к границе, то есть на подгонке.
// Вторая: старт луча смещается хешем ОТ ЭКРАННОЙ ПОЗИЦИИ пикселя. Хеш задумывался постоянным, но
// джиттер апскейлера каждый кадр сдвигает проекцию на долю пикселя, одна и та же точка воды
// попадает в разные пиксели — и постоянный хеш начинает меняться каждый кадр. Усреднить это
// апскейлер не может: вода не пишет ни глубину, ни векторы движения, поэтому шум размазывается
// в пятна, а не сходится.
//
// Бонусом уходит и цена: марш это до 160 итераций на пиксель, а дальняя вода занимает большую часть
// поверхности.
#define WATER_SSR_START		30.0	// метры: докуда отражения считаются полностью
#define WATER_SSR_END		45.0	// метры: дальше только кубмапа, луч не пускается

#define WATER_RYASKA_DRIFT	0.010	// м/с вдоль
#define WATER_RYASKA_SWAY	0.05	// амплитуда качания, метры

#define WATER_LEAVES_NEAR	0.05	// метры глубины, где сор начинается
#define WATER_LEAVES_FAR	4.00	// и где сходит на нет
// ⚠️ Числа В МЕТРАХ и настоящие. Пока глубина считалась вдоль луча взгляда, косинус её сильно
// занижал, и окно 0.02..0.60 работало случайно — по «глубине», которая метрами не была. С честной
// глубиной болото это метр и больше, и прежнее окно отсекало сор везде, кроме самой кромки.
#define WATER_LEAVES_STRENGTH	1.0

// Порог и резкость альфы листа. Текстура декали — листья на мягко затухающем фоне, и с такой альфой
// лист выходит полупрозрачным: сквозь него просвечивает дно со своим волнистым рисунком, и глаз
// читает лист как лежащий ПОД водой. Порог отрезает фон, резкость делает остаток почти непрозрачным —
// дно за листом не видно, и он оказывается на поверхности.
#define WATER_LEAVES_CUT	0.25	// ниже этой альфы — фон, выбрасываем
#define WATER_LEAVES_SHARP	4.0	// во сколько раз круче край

// Масштаб развёртки сора и тины в МЕТРАХ мира: 0.5 = рисунок повторяется каждые два метра.
//
// ⚠️ Сор привязан к МИРУ, а не к развёртке воды. UV воды анимирована — она течёт, — и сор, снятый по
// ней, ехал вместе с водой и читался её частью: волна как будто шла по листу. Мусор на стоячей воде
// стоит на месте, вода движется под ним. Мировая привязка это и даёт, заодно убирая зависимость от
// того, как растянута развёртка на конкретном уровне.
#define WATER_DEBRIS_SCALE	0.5

// Разбиение повтора. Одна выборка по мировым координатам даёт ровную решётку — «шахматную доску»:
// глаз мгновенно ловит период. Лечится двумя приёмами сразу:
//   1. вторая выборка, ПОВЁРНУТАЯ и с несоизмеримым масштабом. Два периода, не кратные друг другу,
//      совпадают крайне редко, и объединение читается случайным;
//   2. крупная маска плотности из той же текстуры на очень низкой частоте — сор собирается в пятна,
//      как его сбивает ветром, а не лежит ровным слоем. Именно ровность и выдаёт узор.
#define WATER_DEBRIS_ROT2	0.63	// масштаб второй выборки; НЕ делать кратным единице
#define WATER_DEBRIS_PATCH	0.13	// частота пятен: меньше — пятна крупнее
#define WATER_DEBRIS_PATCH_MIN	0.25	// сколько сора остаётся в «пустых» местах

// [DA_PORT] 4. Тина на дне. Отдельный слой ПОД сором: тот плавает на поверхности и живёт на мелководье,
// а тина набирает силу с глубиной. Рисунок берём из той же текстуры сора, но на крупном масштабе —
// получаются мягкие пятна, а не листья. Красится своим цветом, поэтому от исходной картинки нужна
// только альфа.
//
// Кладётся ДО тумана и до сора: тина под водой, её толща обязана приглушать.
#define WATER_SILT_TILE		0.35	// меньше — крупнее пятна
#define WATER_SILT_DEPTH	0.35	// метры: с какой глубины тина набирает силу
#define WATER_SILT_STRENGTH	0.45
#define WATER_SILT_COLOR	float3(0.20, 0.28, 0.16)

// [DA_PORT] 5. Отсечение по альфе — предложение автора мода.
//
// Кромка воды и её плоскость за берегом уходят в почти нулевую альфу, но пиксель всё равно рисуется:
// он попадает в смешивание и в сортировку, даёт еле заметную плёнку по краю и лишнюю работу на
// каждом кадре. clip() выбрасывает такие пиксели целиком, до блендинга.
//
// Порог держать МАЛЕНЬКИМ: он режет по итоговой альфе, в которую уже вошёл туман (alpha *= fog*fog),
// а значит на дальней воде альфа мала сама по себе. Слишком большой порог оставит дыру вместо реки.
// [DA_PORT] ⚠ ВЫКЛЮЧЕНО (0). Это и был источник мерцания воды при апскейлерах.
//
// clip() решает судьбу пикселя по альфе, а альфа собирается из глубины дна, которую шейдер берёт из
// G-буфера по проекционным координатам. Джиттер апскейлера каждый кадр сдвигает эту выборку на долю
// пикселя — глубина скачет, за ней альфа, и пиксели у порога то рисуются, то выбрасываются. На маске
// реактивности это видно прямо: рваные края, дыры, площадь воды гуляет от кадра к кадру.
//
// Порог мал, но и альфа дальней воды мала: она домножается на квадрат тумана, поэтому у порога
// оказывается не кромка, а целые области — тем большие, чем гуще туман и дальше вода.
//
// Убирать отсечение безопасно: пиксель с нулевой альфой при srcalpha/invsrcalpha не меняет кадр, а
// глубину вода и так не пишет. Платим лишь заполнением на почти прозрачных пикселях.
//
// Ненулевое значение вернёт и отсечение, и мерцание вместе с ним.
#define WATER_ALPHA_CLIP	0.0

// 3. Sun glint. There is a moon road below but nothing for the sun, so daytime water never catches the
//    light. Tight exponent so it stays a glitter track rather than a wash.
#define WATER_SUN_POWER		280.0
#define WATER_SUN_STRENGTH	2.6

// [DA_PORT] ---- Стоячая вода: студень и ряска -----------------------------------------------------
// Отдельный профиль для effects\waterstuden и effects\waterryaska. Обе поверхности — застоявшаяся
// вода: болотная жижа Свалки и Тёмной долины, залитые низы Агропрома и его подземки, ряска на
// Генераторах, студень на Юпитере. Ей не идёт тот же фильтр, что проточной: в стоячей воде взвесь,
// поэтому цвет уходит в жёлто-зелёный, а глубина набирается быстрее — дно пропадает через полметра,
// а не через три.
//
// Профиль включает дефайн DA_WATER_GREEN, его ставит water_green.ps. Проточная вода (effects\water)
// идёт мимо и остаётся ровно такой, какой была.
#ifdef DA_WATER_GREEN
#undef  WATER_TINT_SHALLOW
#define WATER_TINT_SHALLOW	float3(0.13, 0.20, 0.08)	// у берега: жижа, зелень с жёлтым
#undef  WATER_TINT_DEEP
#define WATER_TINT_DEEP		float3(0.040, 0.100, 0.030)	// глубина: тёмно-зелёная, синевы нет вовсе
#undef  WATER_TINT_FALLOFF
#define WATER_TINT_FALLOFF	0.55						// взвесь: глубинный цвет забирает почти сразу
#undef  WATER_FOAM_COLOR
#define WATER_FOAM_COLOR	float3(0.50, 0.54, 0.40)	// кайма у берега не белая, а зеленоватая
#undef  WATER_FOAM_STRENGTH
#define WATER_FOAM_STRENGTH	0.55
#undef  WATER_SUN_STRENGTH
#define WATER_SUN_STRENGTH	1.6							// зеркалит слабее проточной
#endif

#endif	// SETTINGS_DA_WATER_H
